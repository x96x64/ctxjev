import { excerpt, isSubstantiveMessage, toolEntryContent, toolResultText } from './entryText.js'
import type { Entry } from './types.js'

/**
 * Parses Claude Code's session log (one JSON record per line) into `Entry[]`. The format is
 * internal to Claude Code and undocumented, so all knowledge of it stays in this module.
 *
 * Entries are user chat messages, assistant text, and tool calls (a `tool_use` joined with its
 * `tool_result`). Thinking, attachments, bookkeeping records, text Claude Code itself writes into
 * the user turn, and subagent sidechains are skipped: a subagent's result already appears in the
 * main thread as a tool call.
 */

type KnownContentBlock =
  | { type: 'text'; text: string }
  | { type: 'thinking'; thinking: string }
  | { type: 'tool_use'; id: string; name: string; input: unknown }
  | { type: 'tool_result'; tool_use_id: string; content: string | Array<{ type: string; text?: string }>; is_error?: boolean }

type TranscriptRecord = {
  type: string
  subtype?: string
  uuid?: string
  timestamp?: string
  isSidechain?: boolean
  /** Written by Claude Code, not the user: the local-command caveat, an expanded skill's body, … */
  isMeta?: boolean
  isCompactSummary?: boolean
  message?: { role: string; content: string | unknown[] }
}

function asKnownBlock(raw: unknown): KnownContentBlock | undefined {
  if (typeof raw !== 'object' || raw === null || !('type' in raw)) return undefined
  return raw as KnownContentBlock
}

function parseLines(jsonl: string): TranscriptRecord[] {
  const records: TranscriptRecord[] = []
  for (const line of jsonl.split('\n')) {
    if (!line.trim()) continue
    try {
      const record: unknown = JSON.parse(line)
      if (typeof record === 'object' && record !== null) records.push(record as TranscriptRecord)
    } catch {
      // a malformed or truncated line shouldn't take down the whole parse
    }
  }
  return records
}

const COMPACT_SUMMARY_PREFIX = 'This session is being continued from a previous conversation'

// Everything before the most recent compaction is already out of context — only what follows it is.
function isCompactionBoundary(record: TranscriptRecord): boolean {
  if (record.type === 'system' && record.subtype === 'compact_boundary') return true
  if (record.type !== 'user') return false
  if (record.isCompactSummary) return true
  return userTexts(record)[0]?.trimStart().startsWith(COMPACT_SUMMARY_PREFIX) ?? false
}

/** The text a user record carries, as a string message or its text blocks. */
function userTexts(record: TranscriptRecord): string[] {
  const content = record.message?.content
  if (typeof content === 'string') return [userText(content)]
  if (!Array.isArray(content)) return []
  return content.flatMap((raw) => {
    const block = asKnownBlock(raw)
    return block?.type === 'text' ? [userText(block.text)] : []
  })
}

// Text Claude Code writes into the user turn itself: a local command's output, an interrupt notice.
const HARNESS_TEXT = /^(?:<local-command-(?:stdout|stderr|caveat)>|\[Request interrupted by user|Caveat: The messages below were generated by the user while running local commands)/

function isHarnessText(text: string): boolean {
  return HARNESS_TEXT.test(text.trimStart())
}

// Claude Code wraps text the user pasted in <pasted_content id="…"> tags; only what's inside is theirs.
const PASTED_CONTENT_TAG = /<\/?pasted_content(?:\s+id="[^"]*")?\s*>/g

function userText(text: string): string {
  return text.replace(PASTED_CONTENT_TAG, '').trim()
}

function toTimestampMs(timestamp: string | undefined): number {
  if (!timestamp) return 0
  const parsed = Date.parse(timestamp)
  return Number.isNaN(parsed) ? 0 : parsed
}

export type ParseClaudeCodeTranscriptOptions = {
  /**
   * Fills in each entry's `sourceTokens` — pass `estimateTokens`. A parameter rather than a direct
   * import so the Claude Code plugin, which never shows token counts, doesn't bundle a tokenizer.
   */
  countTokens?: (text: string) => number
  /** Told about anything odd in the log that was worked around rather than failed on. */
  onWarning?: (message: string) => void
}

export function parseClaudeCodeTranscript(jsonl: string, options: ParseClaudeCodeTranscriptOptions = {}): Entry[] {
  const { countTokens, onWarning } = options
  const count = (text: string) => (countTokens ? { sourceTokens: countTokens(text) } : {})
  const entries: Entry[] = []
  // `at`: how many entries came before this tool_use, so a call that never gets its result can be
  // put back where it happened rather than after everything else.
  const pendingToolUse = new Map<string, { name: string; input: unknown; timestamp: number; at: number }>()
  // A record without a usable timestamp takes the previous one's, so it keeps its place in the
  // order instead of reading as the oldest entry in the batch.
  let lastTimestamp = 0

  parseLines(jsonl).forEach((record, line) => {
    if (record.isSidechain || record.isMeta) return

    if (isCompactionBoundary(record)) {
      entries.length = 0
      pendingToolUse.clear()
      return
    }

    const timestamp = toTimestampMs(record.timestamp) || lastTimestamp
    lastTimestamp = timestamp
    const recordId = record.uuid ?? `line-${line}`
    const content = record.message?.content

    if (record.type === 'user' && typeof content === 'string') {
      const text = userText(content)
      if (!isHarnessText(text)) entries.push({ id: recordId, role: 'user', content: excerpt(text), timestamp, ...count(text) })
      return
    }

    if (!Array.isArray(content)) return

    for (const [index, raw] of content.entries()) {
      const block = asKnownBlock(raw)
      if (!block) continue

      // A user turn's content is array-shaped whenever it carries more than plain text (an
      // attachment alongside a text block, for example).
      if (block.type === 'text' && (record.type === 'assistant' || record.type === 'user')) {
        const text = record.type === 'user' ? userText(block.text) : block.text
        if (record.type === 'user' && isHarnessText(text)) continue
        entries.push({
          id: `${recordId}:text:${index}`,
          role: record.type === 'user' ? 'user' : 'assistant',
          content: excerpt(text),
          timestamp,
          ...count(text),
        })
      } else if (block.type === 'tool_use') {
        pendingToolUse.set(block.id, { name: block.name, input: block.input, timestamp, at: entries.length })
      } else if (block.type === 'tool_result') {
        const pending = pendingToolUse.get(block.tool_use_id)
        pendingToolUse.delete(block.tool_use_id)
        const name = pending?.name ?? 'unknown_tool'
        const resultText = toolResultText(block.content)
        entries.push({
          id: block.tool_use_id,
          role: 'tool',
          toolName: name,
          content: toolEntryContent(name, pending?.input, { text: resultText, isError: block.is_error }),
          timestamp: pending?.timestamp ?? timestamp,
          ...count(`${JSON.stringify(pending?.input ?? {})}${resultText}`),
        })
      }
    }
  })

  // A tool_use that never got its tool_result (the log ends mid-call, or the call was interrupted)
  // still took up context. It goes back where it was made: appended last, recency (which ranks by
  // position) would take it for the newest entry in the batch. Inserted last-first, so calls made
  // at the same point keep their order.
  for (const [toolUseId, pending] of [...pendingToolUse].reverse()) {
    entries.splice(pending.at, 0, {
      id: toolUseId,
      role: 'tool',
      toolName: pending.name,
      content: toolEntryContent(pending.name, pending.input, undefined),
      timestamp: pending.timestamp,
      ...count(JSON.stringify(pending.input ?? {})),
    })
  }

  return keepLastById(entries, onWarning)
}

/**
 * One entry per id, the last one, where it appears. Entry ids come from the log (a record's uuid, a
 * tool_use_id), and a record written twice would otherwise make scoreEntries() reject the whole
 * transcript as having duplicate ids — for the plugin, preserving nothing at all.
 */
function keepLastById(entries: Entry[], onWarning?: (message: string) => void): Entry[] {
  const lastIndex = new Map<string, number>()
  entries.forEach((entry, i) => lastIndex.set(entry.id, i))
  if (lastIndex.size === entries.length) return entries
  const repeated = [...new Set(entries.filter((entry, i) => lastIndex.get(entry.id) !== i).map((entry) => `"${entry.id}"`))]
  onWarning?.(
    `${entries.length - lastIndex.size} transcript record(s) repeat an earlier id (${repeated.slice(0, 3).join(', ')}${repeated.length > 3 ? ', …' : ''}); kept the last of each`,
  )
  return entries.filter((entry, i) => lastIndex.get(entry.id) === i)
}

/** When the session this transcript belongs to started — the first record carrying a timestamp. */
export function transcriptStartTime(jsonl: string): number | undefined {
  for (const record of parseLines(jsonl)) {
    const ms = toTimestampMs(record.timestamp)
    if (ms > 0) return ms
  }
  return undefined
}

/** A real slash command's own token has no further "/" or whitespace in it, e.g. "/compact" or
 * "/ctxjev:set-goal" — unlike a path a user might type mid-sentence ("/etc/hosts isn't read"). */
const SLASH_COMMAND_TOKEN = /^\/[a-zA-Z][\w-]*(:[\w-]+)*$/

function isSlashCommand(content: string): boolean {
  const trimmed = content.trim()
  if (trimmed.includes('<command-name>')) return true
  // Only a bare command ("/compact") is certain; "/deploy the hotfix now" may be a sentence, and
  // real invocations with arguments are wrapped in <command-name> anyway.
  const words = trimmed.split(/\s+/)
  return words.length === 1 && SLASH_COMMAND_TOKEN.test(words[0])
}

// What the user ran in bash mode (`!npm test`) and its output: history, but not a request.
const BASH_MODE = /^<bash-(?:input|stdout|stderr)>/

/** Whether a user entry says what the user wants, rather than running a command (a slash command, bash mode). */
export function isGoalCandidate(content: string): boolean {
  return !isSlashCommand(content) && !BASH_MODE.test(content.trimStart())
}

export type InferGoalOptions = {
  /** The session's original request, when it's no longer among `entries` (see `findOriginalTask`). */
  task?: string
}

/**
 * A fallback goal when none was set explicitly: the task (the first user message that describes
 * something) plus the most recent one (where the work is now). The latest alone is usually a step
 * like "also check the tests". Short acknowledgments are skipped unless nothing longer exists.
 */
export function inferGoalFromEntries(entries: Entry[], options: InferGoalOptions = {}): string | undefined {
  const candidates = entries.filter((e) => e.role === 'user' && isGoalCandidate(e.content))
  const substantive = candidates.filter((e) => isSubstantiveMessage(e.content))
  const latest = (substantive.at(-1) ?? candidates.at(-1))?.content
  const task = options.task ?? substantive[0]?.content
  if (!latest) return task
  return task && task !== latest ? `${task}\n\nLatest instruction: ${latest}` : latest
}

/**
 * The session's first substantive request, from the whole log — including what earlier compactions
 * removed from context, which `parseClaudeCodeTranscript` leaves out. After a second compaction the
 * entries alone no longer contain the original task.
 */
export function findOriginalTask(jsonl: string): string | undefined {
  for (const record of parseLines(jsonl)) {
    if (record.type !== 'user' || record.isSidechain || record.isMeta || isCompactionBoundary(record)) continue
    for (const text of userTexts(record)) {
      if (!isHarnessText(text) && isGoalCandidate(text) && isSubstantiveMessage(text)) return excerpt(text)
    }
  }
  return undefined
}

const SET_GOAL_SKILL = /^(?:ctxjev:)?set-goal$/
const SET_GOAL_COMMAND = /<command-name>\/ctxjev:set-goal<\/command-name>/
const COMMAND_ARGS = /<command-args>([\s\S]*?)<\/command-args>/

/**
 * The goal set with `/ctxjev:set-goal <text>` most recently in this session, read from the log
 * itself: the command's own record (or the Skill tool call, when Claude invoked it), so a goal
 * belongs to the session it was set in and survives compaction.
 */
export function findExplicitGoal(jsonl: string): string | undefined {
  let goal: string | undefined
  for (const record of parseLines(jsonl)) {
    if (record.isSidechain) continue
    if (record.type === 'user') {
      for (const text of userTexts(record)) {
        const args = SET_GOAL_COMMAND.test(text) ? text.match(COMMAND_ARGS)?.[1].trim() : undefined
        if (args) goal = args
      }
    } else if (record.type === 'assistant' && Array.isArray(record.message?.content)) {
      for (const raw of record.message.content) {
        const block = asKnownBlock(raw)
        if (block?.type !== 'tool_use' || block.name !== 'Skill') continue
        const input = block.input as { skill?: unknown; args?: unknown } | undefined
        const args = typeof input?.args === 'string' ? input.args.trim() : ''
        if (typeof input?.skill === 'string' && SET_GOAL_SKILL.test(input.skill) && args) goal = args
      }
    }
  }
  return goal
}

export type ClaudeCodeGoal = { goal: string; source: 'explicit' | 'inferred' }

/** The goal to score a Claude Code session against: `/ctxjev:set-goal`'s, or else inferred. */
export function resolveClaudeCodeGoal(jsonl: string, entries: Entry[]): ClaudeCodeGoal | undefined {
  const explicit = findExplicitGoal(jsonl)
  if (explicit) return { goal: explicit, source: 'explicit' }
  const inferred = inferGoalFromEntries(entries, { task: findOriginalTask(jsonl) })
  return inferred ? { goal: inferred, source: 'inferred' } : undefined
}
